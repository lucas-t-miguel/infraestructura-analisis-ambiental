-- Esquema del Data Warehouse
CREATE SCHEMA IF NOT EXISTS dw;

DROP VIEW IF EXISTS dw.v_dw_resumen_anual;
DROP VIEW IF EXISTS dw.v_dw_resumen_mensual;
DROP VIEW IF EXISTS dw.v_dw_resumen_diario;
DROP VIEW IF EXISTS dw.v_dw_franjas_horarias;
