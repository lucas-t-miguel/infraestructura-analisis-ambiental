-- DIMENSIONES
CREATE TABLE dw.dim_tiempo (
    tiempo_key          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha               DATE NOT NULL,
    hora                SMALLINT NOT NULL,
    anio                SMALLINT NOT NULL,
    trimestre           SMALLINT NOT NULL,
    mes                 SMALLINT NOT NULL,
    nombre_mes          VARCHAR(20) NOT NULL,
    semana_anio         SMALLINT NOT NULL,
    dia_mes             SMALLINT NOT NULL,
    dia_semana          SMALLINT NOT NULL,
    nombre_dia_semana   VARCHAR(20) NOT NULL,
    es_fin_semana       BOOLEAN NOT NULL,
    franja_horaria      VARCHAR(20) NOT NULL,
    etiqueta_hora       VARCHAR(5) NOT NULL,
    CONSTRAINT uq_dim_tiempo_fecha_hora UNIQUE (fecha, hora)
);

CREATE INDEX idx_dim_tiempo_fecha ON dw.dim_tiempo (fecha);
CREATE INDEX idx_dim_tiempo_mes ON dw.dim_tiempo (anio, mes);
CREATE INDEX idx_dim_tiempo_franja ON dw.dim_tiempo (franja_horaria);

CREATE TABLE dw.dim_fuente (
    fuente_key          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_fuente       VARCHAR(40) NOT NULL,
    nombre_fuente       VARCHAR(120) NOT NULL,
    tipo_fuente         VARCHAR(40),
    url_referencia      VARCHAR(255),
    activa              BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_dim_fuente_codigo UNIQUE (codigo_fuente)
);

CREATE TABLE dw.dim_estacion (
    estacion_key        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_estacion     VARCHAR(40) NOT NULL,
    nombre_estacion     VARCHAR(120) NOT NULL,
    municipio           VARCHAR(100) DEFAULT 'Madrid',
    latitud             NUMERIC(9,6),
    longitud            NUMERIC(9,6),
    activa              BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_dim_estacion_codigo UNIQUE (codigo_estacion)
);

CREATE TABLE dw.dim_magnitud (
    magnitud_key        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_magnitud     VARCHAR(20) NOT NULL,
    nombre_magnitud     VARCHAR(120) NOT NULL,
    unidad              VARCHAR(30),
    descripcion         VARCHAR(255),
    CONSTRAINT uq_dim_magnitud_codigo UNIQUE (codigo_magnitud)
);

-- TABLA DE HECHOS
CREATE TABLE dw.fact_ambiental_horaria (
    hecho_key           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tiempo_key          INTEGER NOT NULL,
    fuente_key          SMALLINT NOT NULL,
    estacion_key        INTEGER NOT NULL,
    magnitud_key        INTEGER NOT NULL,

    temperatura_c       NUMERIC(6,2),
    humedad_pct         NUMERIC(6,2),
    viento_kmh          NUMERIC(6,2),
    presion_hpa         NUMERIC(8,2),
    precipitacion_mm    NUMERIC(8,2),
    valor_magnitud      NUMERIC(10,3),

    fecha_carga         TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    origen_lake_path    VARCHAR(255),

    CONSTRAINT fk_fact_tiempo
        FOREIGN KEY (tiempo_key) REFERENCES dw.dim_tiempo (tiempo_key),
    CONSTRAINT fk_fact_fuente
        FOREIGN KEY (fuente_key) REFERENCES dw.dim_fuente (fuente_key),
    CONSTRAINT fk_fact_estacion
        FOREIGN KEY (estacion_key) REFERENCES dw.dim_estacion (estacion_key),
    CONSTRAINT fk_fact_magnitud
        FOREIGN KEY (magnitud_key) REFERENCES dw.dim_magnitud (magnitud_key),
    CONSTRAINT uq_fact_grano UNIQUE (tiempo_key, fuente_key, estacion_key, magnitud_key)
);

CREATE INDEX idx_fact_tiempo ON dw.fact_ambiental_horaria (tiempo_key);
CREATE INDEX idx_fact_fuente ON dw.fact_ambiental_horaria (fuente_key);
CREATE INDEX idx_fact_estacion ON dw.fact_ambiental_horaria (estacion_key);
CREATE INDEX idx_fact_magnitud ON dw.fact_ambiental_horaria (magnitud_key);
CREATE INDEX idx_fact_tiempo_fuente ON dw.fact_ambiental_horaria (tiempo_key, fuente_key);

