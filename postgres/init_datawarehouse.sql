-- VISTAS ANALÍTICAS (OLAP)
CREATE OR REPLACE VIEW dw.v_dw_resumen_diario AS
SELECT
    t.fecha,
    ROUND(AVG(f.temperatura_c), 2)    AS temp_media,
    ROUND(MIN(f.temperatura_c), 2)    AS temp_min,
    ROUND(MAX(f.temperatura_c), 2)    AS temp_max,
    ROUND(AVG(f.humedad_pct), 2)      AS humedad_media,
    ROUND(SUM(f.precipitacion_mm), 2) AS precipitacion_total,
    ROUND(AVG(f.viento_kmh), 2)       AS viento_medio,
    ROUND(AVG(f.presion_hpa), 2)      AS presion_media,
    COUNT(*)                          AS total_registros
FROM dw.fact_ambiental_horaria f
JOIN dw.dim_tiempo t ON t.tiempo_key = f.tiempo_key
GROUP BY t.fecha;

CREATE OR REPLACE VIEW dw.v_dw_fuente_diaria AS
SELECT
    t.fecha,
    s.codigo_fuente,
    s.nombre_fuente,
    ROUND(AVG(f.temperatura_c), 2)    AS temp_media,
    ROUND(AVG(f.humedad_pct), 2)      AS humedad_media,
    ROUND(SUM(f.precipitacion_mm), 2) AS precipitacion_total,
    ROUND(AVG(f.valor_magnitud), 3)   AS valor_magnitud_medio,
    COUNT(*)                          AS total_registros
FROM dw.fact_ambiental_horaria f
JOIN dw.dim_tiempo t ON t.tiempo_key = f.tiempo_key
JOIN dw.dim_fuente s ON s.fuente_key = f.fuente_key
GROUP BY t.fecha, s.codigo_fuente, s.nombre_fuente;

CREATE OR REPLACE VIEW dw.v_dw_franjas_horarias AS
SELECT
    t.fecha,
    t.franja_horaria,
    ROUND(AVG(f.temperatura_c), 2)    AS temp_media,
    ROUND(AVG(f.humedad_pct), 2)      AS humedad_media,
    ROUND(SUM(f.precipitacion_mm), 2) AS precipitacion_total,
    COUNT(*)                          AS total_registros
FROM dw.fact_ambiental_horaria f
JOIN dw.dim_tiempo t ON t.tiempo_key = f.tiempo_key
GROUP BY t.fecha, t.franja_horaria;

CREATE OR REPLACE VIEW dw.v_dw_resumen_mensual AS
SELECT
    t.anio,
    t.mes,
    t.nombre_mes,
    ROUND(AVG(f.temperatura_c), 2)    AS temp_media,
    ROUND(MIN(f.temperatura_c), 2)    AS temp_min,
    ROUND(MAX(f.temperatura_c), 2)    AS temp_max,
    ROUND(AVG(f.humedad_pct), 2)      AS humedad_media,
    ROUND(SUM(f.precipitacion_mm), 2) AS precipitacion_total,
    COUNT(*)                          AS total_registros
FROM dw.fact_ambiental_horaria f
JOIN dw.dim_tiempo t ON t.tiempo_key = f.tiempo_key
GROUP BY t.anio, t.mes, t.nombre_mes;

CREATE OR REPLACE VIEW dw.v_dw_resumen_anual AS
SELECT
    t.anio,
    ROUND(AVG(f.temperatura_c), 2)    AS temp_media,
    ROUND(MIN(f.temperatura_c), 2)    AS temp_min,
    ROUND(MAX(f.temperatura_c), 2)    AS temp_max,
    ROUND(AVG(f.humedad_pct), 2)      AS humedad_media,
    ROUND(SUM(f.precipitacion_mm), 2) AS precipitacion_total,
    COUNT(*)                          AS total_registros
FROM dw.fact_ambiental_horaria f
JOIN dw.dim_tiempo t ON t.tiempo_key = f.tiempo_key
GROUP BY t.anio;


CREATE TABLE dw.stg_curated_csv (
    fecha               DATE NOT NULL,
    hora                SMALLINT NOT NULL,
    temperatura_c       NUMERIC(6,2),
    humedad_pct         NUMERIC(6,2),
    viento_kmh          NUMERIC(6,2),
    presion_hpa         NUMERIC(8,2),
    precipitacion_mm    NUMERIC(8,2),
    madrid_magnitud     VARCHAR(20),
    madrid_estacion     VARCHAR(120)
);

INSERT INTO dw.dim_tiempo (
    fecha,
    hora,
    anio,
    trimestre,
    mes,
    nombre_mes,
    semana_anio,
    dia_mes,
    dia_semana,
    nombre_dia_semana,
    es_fin_semana,
    franja_horaria,
    etiqueta_hora
)
SELECT DISTINCT
    s.fecha,
    s.hora,
    EXTRACT(YEAR FROM s.fecha)::smallint,
    EXTRACT(QUARTER FROM s.fecha)::smallint,
    EXTRACT(MONTH FROM s.fecha)::smallint,
    CASE EXTRACT(MONTH FROM s.fecha)::int
        WHEN 1 THEN 'enero'
        WHEN 2 THEN 'febrero'
        WHEN 3 THEN 'marzo'
        WHEN 4 THEN 'abril'
        WHEN 5 THEN 'mayo'
        WHEN 6 THEN 'junio'
        WHEN 7 THEN 'julio'
        WHEN 8 THEN 'agosto'
        WHEN 9 THEN 'septiembre'
        WHEN 10 THEN 'octubre'
        WHEN 11 THEN 'noviembre'
        WHEN 12 THEN 'diciembre'
    END,
    EXTRACT(WEEK FROM s.fecha)::smallint,
    EXTRACT(DAY FROM s.fecha)::smallint,
    EXTRACT(DOW FROM s.fecha)::smallint,
    CASE EXTRACT(DOW FROM s.fecha)::int
        WHEN 0 THEN 'domingo'
        WHEN 1 THEN 'lunes'
        WHEN 2 THEN 'martes'
        WHEN 3 THEN 'miercoles'
        WHEN 4 THEN 'jueves'
        WHEN 5 THEN 'viernes'
        WHEN 6 THEN 'sabado'
    END,
    CASE WHEN EXTRACT(DOW FROM s.fecha)::int IN (0, 6) THEN TRUE ELSE FALSE END,
    CASE
        WHEN s.hora BETWEEN 6 AND 11 THEN 'manana'
        WHEN s.hora BETWEEN 12 AND 19 THEN 'tarde'
        ELSE 'noche'
    END,
    LPAD(s.hora::text, 2, '0')
FROM dw.stg_curated_csv s
ON CONFLICT (fecha, hora) DO NOTHING;

INSERT INTO dw.dim_estacion (codigo_estacion, nombre_estacion, municipio, activa)
SELECT DISTINCT
    COALESCE(NULLIF(TRIM(s.madrid_estacion), ''), 'NA'),
    COALESCE(NULLIF(TRIM(s.madrid_estacion), ''), 'Estacion no informada'),
    'Madrid',
    TRUE
FROM dw.stg_curated_csv s
ON CONFLICT (codigo_estacion) DO UPDATE
SET nombre_estacion = EXCLUDED.nombre_estacion,
    municipio = EXCLUDED.municipio,
    activa = EXCLUDED.activa;

INSERT INTO dw.dim_magnitud (codigo_magnitud, nombre_magnitud, unidad, descripcion)
SELECT DISTINCT
    COALESCE(NULLIF(TRIM(s.madrid_magnitud), ''), 'NA'),
    CASE
        WHEN NULLIF(TRIM(s.madrid_magnitud), '') IS NULL THEN 'Magnitud no informada'
        ELSE CONCAT('Magnitud ', TRIM(s.madrid_magnitud))
    END,
    NULL,
    'Magnitud procedente del portal municipal'
FROM dw.stg_curated_csv s
ON CONFLICT (codigo_magnitud) DO UPDATE
SET nombre_magnitud = EXCLUDED.nombre_magnitud,
    unidad = EXCLUDED.unidad,
    descripcion = EXCLUDED.descripcion;

INSERT INTO dw.fact_ambiental_horaria (
    tiempo_key,
    fuente_key,
    estacion_key,
    magnitud_key,
    temperatura_c,
    humedad_pct,
    viento_kmh,
    presion_hpa,
    precipitacion_mm,
    valor_magnitud,
    origen_lake_path
)
SELECT
    t.tiempo_key,
    f.fuente_key,
    e.estacion_key,
    m.magnitud_key,
    s.temperatura_c,
    s.humedad_pct,
    s.viento_kmh,
    s.presion_hpa,
    s.precipitacion_mm,
    NULL,
    'curated-zone/.../datos.csv'
FROM dw.stg_curated_csv s
JOIN dw.dim_tiempo t
  ON t.fecha = s.fecha
 AND t.hora = s.hora
JOIN dw.dim_fuente f
  ON f.codigo_fuente = 'fusion_curated'
JOIN dw.dim_estacion e
  ON e.codigo_estacion = COALESCE(NULLIF(TRIM(s.madrid_estacion), ''), 'NA')
JOIN dw.dim_magnitud m
  ON m.codigo_magnitud = COALESCE(NULLIF(TRIM(s.madrid_magnitud), ''), 'NA')
ON CONFLICT (tiempo_key, fuente_key, estacion_key, magnitud_key) DO UPDATE
SET temperatura_c = EXCLUDED.temperatura_c,
    humedad_pct = EXCLUDED.humedad_pct,
    viento_kmh = EXCLUDED.viento_kmh,
    presion_hpa = EXCLUDED.presion_hpa,
    precipitacion_mm = EXCLUDED.precipitacion_mm,
    valor_magnitud = EXCLUDED.valor_magnitud,
    origen_lake_path = EXCLUDED.origen_lake_path,
    fecha_carga = CURRENT_TIMESTAMP;

DELETE FROM dw.stg_curated_csv;
